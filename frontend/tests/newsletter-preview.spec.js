  await expect(wide.locator('iframe')).toHaveCSS('width', '375px')
  await wide.getByRole('button', { name: '데스크톱 640px' }).click()
  await expect(wide.locator('iframe')).toHaveCSS('width', '640px')
  await page.keyboard.press('Escape')
  await expect(wide).toBeHidden()
  await page.getByRole('button', { name: '모바일', exact: true }).click()
  await expect(frame.locator('body')).toHaveCSS('background-color', 'rgb(255, 255, 255)')
  const overflow = await frame.locator('html').evaluate(el => el.scrollWidth > el.clientWidth)
  expect(overflow).toBe(false)
  await page.getByLabel('사진 추가').setInputFiles({ name: 'extra.png', mimeType: 'image/png', buffer: Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+a/RsAAAAASUVORK5CYII=', 'base64') })
  await expect(frame.locator('img')).toHaveCount(2)
  await expect(frame.locator('img').nth(1)).toHaveAttribute('src', /^blob:/)
  await page.getByRole('button', { name: '미리보기 Deutsch', exact: true }).click()
  await expect(frame.getByRole('heading', { level: 1 })).toHaveText('KLANG IN BEWEGUNG')
  await expect(frame.getByText('Abmelden (Vorschau)', { exact: true })).toBeVisible()
  await expect(frame.getByRole('link', { name: 'Abmelden (Vorschau)' })).toHaveCount(0)
  await page.getByRole('button', { name: '영상 링크 추가', exact: true }).click()
  await page.getByLabel('영상 링크 1', { exact: true }).fill('http://insecure.example.com')
